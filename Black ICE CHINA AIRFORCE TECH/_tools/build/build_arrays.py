# scripted GUI: copy BIAD's luftwaffe folder block, rename to our folder
# --------------------------------------------------------------------------
def extract_block(text, start_marker):
    i = text.index(start_marker)
    brace = text.index("{", i)
    depth = 1
    j = brace + 1
    while j < len(text) and depth:
        if text[j] == "{":
            depth += 1
        elif text[j] == "}":
            depth -= 1
        j += 1
    return text[i:j]


def emit_scripted_gui():
    src = os.path.join(BIAD, "common", "scripted_guis", "BI_research_scripted_gui.txt")
    text = open(src, encoding="utf-8-sig", errors="replace").read()
    marker = "BI_tech_queue_luftwaffe_folder = {"
    if marker not in text:
        # fall back to any nation air block
        m = re.search(r"BI_tech_queue_\w*air\w*_folder = \{", text)
        if not m:
            raise SystemExit("no folder block found in BIAD scripted GUI")
        marker = m.group(0)
    block = extract_block(text, marker)
    block = block.replace("BI_tech_queue_luftwaffe_folder", "BI_tech_queue_chinaair_folder")
    block = block.replace("luftwaffe_folder", FOLDER)
    # 箭头(add_to_queue)被引擎硬编码读 tech_x/tech_y，改 ax/ay 会整块失效导致箭头消失，
    # 因此箭头位置只能用 PIXEL_ORIGIN_X/Y 整体平移；天数仍用 dx/dy（我们的触发器覆盖）。
    # 把我们的触发器追加到 triggers 块最后，确保覆盖黑冰默认值
    ti = block.find("triggers = {")
    if ti >= 0:
        brace = block.index("{", ti)
        depth = 1
        j = brace + 1
        while j < len(block) and depth:
            if block[j] == "{":
                depth += 1
            elif block[j] == "}":
                depth -= 1
            j += 1
        block = block[: j - 1] + "\n\t\t\tCHI_air_time_estimate = yes\n\t\t" + block[j - 1 :]
    out = [
        "# 中系飞机科技树 / Chinese Aircraft Tech Tree",
        "# 让黑冰的自定义科技界面把 chinaair_folder 画出来",
        "# 由 BIAD 的一个国家空军文件夹块改名派生；字段含义与 BIAD 完全一致",
        "scripted_gui = {",
        block,
        "}",
        "",
    ]
    path = os.path.join(MOD, "common", "scripted_guis", "BI_tech_queue_china_air.txt")
    write(path, "\n".join(out))
    return path, block.count("chinaair_folder")


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", path, len(text), "bytes")


def main():
    techs = parse_our_techs()
    print(f"techs in {FOLDER}: {len(techs)}")
    emit_scripted_effect(techs)
    emit_on_actions(techs)
    emit_history(techs)
    path, n = emit_scripted_gui()
    print(f"scripted gui refs to {FOLDER}: {n}")


if __name__ == "__main__":
    main()
