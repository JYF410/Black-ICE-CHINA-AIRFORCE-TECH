"""Black ICE tech pages are drawn by a *scripted GUI*, not by .gui gridboxes.

Two things are required for a custom folder to render at all:

1. `common/scripted_guis/*.txt` — a copy of one folder block
   (`BI_tech_queue_<folder>`), whose `parent_window_name` is the folder
   container defined in interface/countrytechtreeview.gui.
2. Research arrays — for every tech:
       add_to_array = { global.<folder> = token:<tech> }
       global.tech_x@<tech> / tech_y@ / tech_cost@ / tech_date@
   plus `global.tech_dependents@<prev>` for the prerequisite arrows.

Pixel mapping (derived from BIAD's own array file and the Chinese tank submod):
    tech_x = 327 + folder_x * 70
    tech_y = 165 + folder_y * 70
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLS = os.path.dirname(HERE)
sys.path.insert(0, TOOLS)
sys.path.insert(0, HERE)
import cw_parse as C
from config import (
    MOD, BIAD, FOLDER, ARRAY_EFFECT as EFFECT_NAME,
    ARRAY_FLAG as FLAG, PIXEL_ORIGIN_X as X0, PIXEL_ORIGIN_X_SMALL as X0_SMALL,
    PIXEL_ORIGIN_Y as Y0, SLOT,
    CANVAS_W, CANVAS_H,
)

SMALL_PREFIXES = ("ad_chi_tech_engine_", "ad_chi_tech_gun_", "ad_chi_tech_ord_")


def _x0(tid):
    """配件列用独立基准，飞机列用大格基准。"""
    return X0_SMALL if tid.startswith(SMALL_PREFIXES) else X0


def parse_our_techs():
    path = os.path.join(MOD, "common", "technologies", "CHI_air.txt")
    tree = C.parse_file(path)
    vars_ = C.collect_vars(tree)
    techs = tree.get("technologies")
    out = []
    for tid, blk in techs.items():
        if not isinstance(blk, C.Node):
            continue
        folder = blk.get("folder")
        if not isinstance(folder, C.Node) or folder.get("name") != FOLDER:
            continue
        pos = folder.get("position")
        x = C.resolve(pos.get("x"), vars_)
        y = C.resolve(pos.get("y"), vars_)
        cost = C.resolve(blk.get("research_cost"), vars_)
        year = C.resolve(blk.get("start_year"), vars_)
        unlocks = C.scalars(blk.get("enable_equipments"))
        deps = []
        d = blk.get("dependencies")
        if isinstance(d, C.Node):
            deps = [k for k in d if isinstance(k, str) and not k.startswith("_")]
        out.append(dict(id=tid, x=int(x), y=int(y), cost=cost, year=int(year),
                        unlocks=unlocks, deps=deps))
    return out


def array_body(techs, indent):
    """Return the effect lines that register every tech."""
    i = indent
    lines = []
    lines.append(f"{i}# {len(techs)} 项科技注册进黑冰研究数组")
    for t in techs:
        px = _x0(t["id"]) + t["x"] * SLOT
        py = Y0 + t["y"] * SLOT
        cost = int(round(float(t["cost"]) * 100))
        lines.append(f"{i}add_to_array = {{ global.{FOLDER} = token:{t['id']} }}")
        lines.append(f"{i}set_variable = {{ global.tech_x@{t['id']} = {px} }}")
        lines.append(f"{i}set_variable = {{ global.tech_y@{t['id']} = {py} }}")
        lines.append(f"{i}set_variable = {{ global.tech_cost@{t['id']} = {cost} }}")
        lines.append(f"{i}set_variable = {{ global.tech_date@{t['id']} = {t['year']} }}")
        # 与 BIAD / 坦克子模一致：写入解锁装备数组。
        # 黑冰的 ui_research_time_estimate 靠 tech_unlocks 判断天数位置，
        # 缺了它条目上的箭头/天数/气泡都会对不齐。
        for eq in t["unlocks"]:
            lines.append(f"{i}add_to_array = {{ global.tech_unlocks@{t['id']} = token:{eq} }}")
        for prev in t["deps"]:
            lines.append(
                f"{i}if = {{ limit = {{ NOT = {{ is_in_array = {{ global.tech_dependents@{prev} "
                f"= token:{t['id']} }} }} }} add_to_array = {{ global.tech_dependents@{prev} "
                f"= token:{t['id']} }} }}"
            )
    return lines


def emit_scripted_effect(techs):
    lines = [
        "# 中系飞机科技树 / Chinese Aircraft Tech Tree",
        "# 黑冰自定义科技页面的研究数组注册（脚本效果版本）",
        "# AUTO-GENERATED by _tools/build/build_arrays.py",
        f"{EFFECT_NAME} = {{",
        f"\tif = {{",
        f"\t\tlimit = {{ NOT = {{ has_global_flag = {FLAG} }} }}",
        f"\t\tset_global_flag = {FLAG}",
    ]
    lines += array_body(techs, "\t\t")
    lines += ["\t}", "}", ""]
    path = os.path.join(MOD, "common", "scripted_effects", "zz_CHI_air_research_arrays.txt")
    write(path, "\n".join(lines))
    return path


def emit_on_actions(techs):
    # on_startup has no scope: scripted_effect call fails there, so inline it.
    lines = [
        "# 中系飞机科技树 / Chinese Aircraft Tech Tree",
        "# 黑冰研究数组注册（on_startup 无作用域，必须内联效果）",
        "# AUTO-GENERATED by _tools/build/build_arrays.py",
        "on_actions = {",
        "\ton_startup = {",
        "\t\teffect = {",
        f"\t\t\tif = {{",
        f"\t\t\t\tlimit = {{ NOT = {{ has_global_flag = {FLAG} }} }}",
        f"\t\t\t\tset_global_flag = {FLAG}",
    ]
    lines += array_body(techs, "\t\t\t")
    lines += ["\t\t\t}", "\t\t}", "\t}", "}", ""]
    path = os.path.join(MOD, "common", "on_actions", "zz_CHI_air_array_gen.txt")
